export const dict = (l: Locale): Dict => (l === "en" ? en : de);

export function gradeLabel(l: Locale, grade: string | null) {
  if (!grade) return "—";
  const map = dict(l).grades;
  return grade in map ? map[grade as keyof typeof map] : grade;
}
export function fluorLabel(l: Locale, value: string) {
  const map = dict(l).fluor;
  return value in map ? map[value as keyof typeof map] : value;
}
export function shapeLabel(l: Locale, shape: string) {
  const map = dict(l).shapes;
  return shape in map ? map[shape as keyof typeof map] : shape;
}
export function originLabel(l: Locale, origin: string) {
  if (origin === "lab") return dict(l).origin.lab;
  if (origin === "natural") return dict(l).origin.natural;
  return origin;
}
